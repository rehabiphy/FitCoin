export default function Icon({ name, size = 20, strokeWidth = 2, ...rest }) {
  const Cmp = ICONS[name] || Sparkles;
  return <Cmp size={size} strokeWidth={strokeWidth} aria-hidden="true" {...rest} />;
}

/** Rounded tinted square holding an icon. `color` is a theme colour name. */
export function IconBubble({ name, color = 'primary', size = 44 }) {
  return (
    <span className={`bubble tint-${color}`} style={{ width: size, height: size }}>
      <Icon name={name} size={size * 0.48} />
    </span>
  );
}
